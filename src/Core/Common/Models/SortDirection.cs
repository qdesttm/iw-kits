namespace IWKits.Core.Common.Models;

/// <summary>
/// Specifies the sorting direction for data.
/// </summary>
public enum SortDirection
{
	/// <summary>
	/// Sorts records from smallest to largest.
	/// </summary>
	Ascending,

	/// <summary>
	/// Sorts records from largest to smallest.
	/// </summary>
	Descending
}